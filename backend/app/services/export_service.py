    @staticmethod
    def generate_csv_report(
        db: Session,
        department_id: Optional[int] = None,
        start_date: Optional[str] = None,
        end_date: Optional[str] = None,
        user_id: Optional[int] = None,
        printer_id: Optional[str] = None,
        job_status: Optional[str] = None,
        is_color: Optional[bool] = None,
        period_preset: Optional[str] = None,
        report_type: str = "department",
    ) -> bytes:
        output = io.StringIO()
        writer = SafeCsvWriter(output)

        if report_type == "jobs":
            job_logs = report_service.get_print_job_logs(
                db=db,
                department_id=department_id,
                user_id=user_id,
                printer_id=printer_id,
                job_status=job_status,
                is_color=is_color,
                start_date=start_date,
                end_date=end_date,
                page=1,
                page_size=5000,
            )
            writer.writerow([
                "Job ID",
                "Order ID",
                "Timestamp",
                "Department",
                "Printer",
                "User Name",
                "Roll Number",
                "Document Name",
                "Pages",
                "Copies",
                "Total Sheets",
                "Color Mode",
                "Duplex",
                "Amount INR",
                "Status",
            ])
            for j in job_logs.jobs:
                writer.writerow([
                    j.id,
                    j.order_id,
                    j.created_at,
                    j.department_name,
                    j.printer_name,
                    j.user_name,
                    j.user_roll_number or "",
                    j.document_name,
                    j.pages,
                    j.copies,
                    j.total_sheets,
                    "Color" if j.is_color else "B&W",
                    "Duplex" if j.is_duplex else "Single",
                    j.amount,
                    j.status,
                ])
        elif report_type == "printers":
            analytics = report_service.generate_analytics_report(
                db=db,
                department_id=department_id,
                printer_id=printer_id,
                start_date=start_date,
                end_date=end_date,
                job_status=job_status,
                is_color=is_color,
                period_preset=period_preset,
            )
            writer.writerow([
                "Printer ID",
                "Printer Name",
                "CUPS Queue",
                "Location",
                "Status",
                "Total Jobs",
                "Total Pages",
                "Color Pages",
                "B&W Pages",
                "Utilization Pct",
                "Success Rate Pct",
                "Revenue INR",
            ])
            for p in analytics.printer_stats:
                writer.writerow([
                    p.printer_id,
                    p.printer_name,
                    p.cups_printer_name,
                    p.location or "",
                    p.status,
                    p.total_jobs,
                    p.total_pages,
                    p.color_pages,
                    p.bw_pages,
                    p.utilization_percentage,
                    p.success_rate,
                    p.total_amount,
                ])
        else:
            # Default: Department Performance
            analytics = report_service.generate_analytics_report(
                db=db,
                department_id=department_id,
                printer_id=printer_id,
                start_date=start_date,
                end_date=end_date,
                job_status=job_status,
                is_color=is_color,
                period_preset=period_preset,
            )
            writer.writerow([
                "Department Code",
                "Department Name",
                "Print Jobs",
                "Total Pages",
                "Color Pages",
                "B&W Pages",
                "Revenue INR",
                "Workload Share Pct",
                "Revenue Share Pct",
                "Active Users",
                "Printers Count",
            ])
            for d in analytics.department_performance:
                writer.writerow([
                    d.department_code,
                    d.department_name,
                    d.jobs,
                    d.pages,
                    d.color_pages,
                    d.bw_pages,
                    d.revenue,
                    d.workload_share_pct,
                    d.revenue_share_pct,
                    d.active_users,
                    d.printers_count,
                ])

        return output.getvalue().encode("utf-8")


